#!/usr/bin/env python3
"""DEV evaluation: read every report in devset/out, check known dimensions where they
exist (synthetic truth; DualSense reference), and write evidence/dev_eval.md."""

import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
out = root / "devset" / "out"
truth_path = root / "devset" / "truth" / "synthetic_truth.json"
truth = json.loads(truth_path.read_text()) if truth_path.exists() else {}

KNOWN = {  # reference dimensions for real objects (approximate, from public specs)
    "dualsense_controller": {"bbox_mm": [160, 66, 106], "tol_mm": 6.0,
                             "note": "Sony spec ≈160×66×106 mm; scan excludes stick tops/trigger travel"},
}

rows = []
for rep_path in sorted(out.glob("*/*_report.json")):
    r = json.loads(rep_path.read_text())
    name = Path(r["input_name"]).stem
    bbox = r["after"]["bbox_mm"]
    dim_check = "n/a"
    if r["input_name"] in truth:
        t = truth[r["input_name"]]["truth_bbox_measured"]
        err = max(abs(sorted(bbox)[i] - sorted(t)[i]) for i in range(3))
        dim_check = f"bbox err {err:.2f} mm vs truth {t}"
    elif name in KNOWN:
        k = KNOWN[name]
        err = max(abs(sorted(bbox)[i] - sorted(k["bbox_mm"])[i]) for i in range(3))
        dim_check = f"bbox err {err:.1f} mm vs ref {k['bbox_mm']} (tol {k['tol_mm']})"
    v, d, t, i = r["verdict"], r["deviation"], r["thickness"], r["idealize"]
    rows.append({
        "file": r["input_name"], "class": r["mesh_class"], "watertight": r["after"]["watertight"],
        "printable": v["printable"], "dev_p95": d["p95_mm"], "dev_max": d["max_mm"],
        "within_budget": d["within_budget"], "thin_pct": round(t["below_min_wall_frac"] * 100, 1),
        "min_wall_mm": t["min_mm"], "ideal": f"{i['accepted']}/{i['regions_found']}",
        "runtime_s": r["runtime_s"], "dims": dim_check,
        "reason": v["printable_reason"],
    })

md = ["# DEV evaluation (auto-generated by tool/eval_dev.py)\n",
      "| file | class | watertight | printable | dev p95 | dev max | in budget | thin % | min wall | idealized | s | dimension check |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    md.append(f"| {r['file']} | {r['class']} | {r['watertight']} | {r['printable']} | {r['dev_p95']} | {r['dev_max']} | "
              f"{r['within_budget']} | {r['thin_pct']} | {r['min_wall_mm']} | {r['ideal']} | {r['runtime_s']} | {r['dims']} |")
md.append("\nVerdict reasons:\n")
for r in rows:
    md.append(f"- {r['file']}: {r['reason']}")
n = len(rows)
md.append(f"\nTotals: {n} files; watertight {sum(r['watertight'] for r in rows)}/{n}; printable "
          f"{sum(r['printable'] for r in rows)}/{n}; within deviation budget {sum(r['within_budget'] for r in rows)}/{n}; "
          f"mean runtime {sum(r['runtime_s'] for r in rows)/max(n,1):.2f} s")
(root / "evidence").mkdir(exist_ok=True)
(root / "evidence" / "dev_eval.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
